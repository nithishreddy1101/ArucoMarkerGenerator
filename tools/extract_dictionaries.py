"""Export OpenCV's predefined ArUco / AprilTag dictionaries to js/dictionaries.js.

Each marker is stored as a hex string of its inner n*n bits (row-major,
MSB first, 1 = white). Run with: python3 tools/extract_dictionaries.py
"""
import json
import os

import cv2

aruco = cv2.aruco
draw = getattr(aruco, "generateImageMarker", None) or aruco.drawMarker

# (family key, label, OpenCV constant, list of sub-dictionary sizes)
FAMILIES = [
    ("4X4", "ArUco 4x4", aruco.DICT_4X4_1000, [50, 100, 250, 1000]),
    ("5X5", "ArUco 5x5", aruco.DICT_5X5_1000, [50, 100, 250, 1000]),
    ("6X6", "ArUco 6x6", aruco.DICT_6X6_1000, [50, 100, 250, 1000]),
    ("7X7", "ArUco 7x7", aruco.DICT_7X7_1000, [50, 100, 250, 1000]),
    ("ARUCO_ORIGINAL", "ArUco original", aruco.DICT_ARUCO_ORIGINAL, None),
    ("APRILTAG_16h5", "AprilTag 16h5", aruco.DICT_APRILTAG_16h5, None),
    ("APRILTAG_25h9", "AprilTag 25h9", aruco.DICT_APRILTAG_25h9, None),
    ("APRILTAG_36h10", "AprilTag 36h10", aruco.DICT_APRILTAG_36h10, None),
    ("APRILTAG_36h11", "AprilTag 36h11", aruco.DICT_APRILTAG_36h11, None),
]


def marker_bits(dictionary, marker_id, n):
    img = draw(dictionary, marker_id, n + 2, borderBits=1)
    return [1 if img[r + 1, c + 1] > 127 else 0 for r in range(n) for c in range(n)]


def to_hex(bits):
    pad = (-len(bits)) % 4
    bits = bits + [0] * pad
    return "".join("%x" % int("".join(map(str, bits[i:i + 4])), 2) for i in range(0, len(bits), 4))


def main():
    out = {}
    for key, label, const, sizes in FAMILIES:
        d = aruco.getPredefinedDictionary(const)
        n = d.markerSize
        count = d.bytesList.shape[0]
        # Sanity check: the smaller ArUco dictionaries are prefixes of the 1000 one.
        for size in sizes or []:
            sub = aruco.getPredefinedDictionary(getattr(aruco, "DICT_%s_%d" % (key, size)))
            assert (sub.bytesList == d.bytesList[:size]).all(), (key, size)
        codes = "".join(to_hex(marker_bits(d, i, n)) for i in range(count))
        out[key] = {"label": label, "bits": n, "count": count, "sizes": sizes, "codes": codes}
        print("%-16s %dx%d  %d markers" % (key, n, n, count))

    path = os.path.join(os.path.dirname(__file__), "..", "js", "dictionaries.js")
    with open(path, "w") as f:
        f.write("// Generated by tools/extract_dictionaries.py from OpenCV %s. Do not edit.\n" % cv2.__version__)
        f.write("window.MARKER_FAMILIES = %s;\n" % json.dumps(out, separators=(",", ":")))


if __name__ == "__main__":
    main()
